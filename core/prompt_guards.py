def format_expert_source_lines(citations: list[dict]) -> list[str]:
    lines: list[str] = []
    for c in citations or []:
        filename = (c.get("filename") or "Документ").strip()
        page = c.get("page")
        if page is None or page == "":
            page_label = "стр. —"
        else:
            page_s = str(page)
            page_label = page_s if page_s.startswith("разд.") else f"стр. {page_s}"
        cid = c.get("id")
        ref = f"[{cid}] " if cid is not None else ""
        lines.append(f"{ref}{filename}, {page_label}")
    return lines


def ensure_expert_sources_block(
    answer: str,
    citations: list[dict] | None = None,
    *,
    fallback_lines: list[str] | None = None,
) -> str:
    """Добавить блок «Источники» только если модель его не дала."""
    text = (answer or "").rstrip()
    if re.search(r"(?:\*\*)?Источники\s*:", text, re.IGNORECASE):
        return text
    lines = [ln.strip() for ln in (fallback_lines or []) if ln and ln.strip()]
    if not lines:
        lines = format_expert_source_lines(citations or [])
    if not lines:
        return text
    numbered = []
    for i, ln in enumerate(lines, 1):
        numbered.append(ln if ln.startswith("[") else f"[{i}] {ln}")
    return f"{text}\n\n**Источники:**\n" + "\n".join(numbered)
